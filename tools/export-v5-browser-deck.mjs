#!/usr/bin/env node

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { applyConversationalChunkReplacements } from './lib/v5-chunks.mjs';
import { applyModernLifeCoverage } from './lib/v5-modern-life.mjs';
import { applyRegisterAudit } from './lib/v5-register.mjs';
import {
  applyRomanizationToCards,
  loadRegisterPairPolicy,
  loadRomanizationPolicy
} from './lib/v5-romanization.mjs';
import { applyExampleSentences } from './lib/v5-examples.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');
const v5Dir = path.join(root, 'data', 'v5');
const batchesDir = path.join(v5Dir, 'batches');

const foundation = JSON.parse(fs.readFileSync(path.join(v5Dir, 'deck.json'), 'utf8'));
const registerPolicy = loadRegisterPairPolicy();
const romanPolicy = loadRomanizationPolicy();

function batchKey(name) {
  return name.replace(/(?:\.reviewed|\.compounds|\.registers)?\.mjs$/, '');
}
function precedence(name) {
  if (name.endsWith('.registers.mjs')) return 3;
  if (name.endsWith('.compounds.mjs')) return 2;
  if (name.endsWith('.reviewed.mjs')) return 1;
  return 0;
}
function batchStart(name) {
  const match = name.match(/^core-(\d+)/);
  return match ? Number(match[1]) : Number.MAX_SAFE_INTEGER;
}
function stageFor(position) {
  if (position <= 100) return 'Start Here';
  if (position <= 300) return 'Core Conversation';
  if (position <= 750) return 'Daily Life';
  if (position <= 1250) return 'Practical Life';
  if (position <= 1750) return 'Wider Conversation';
  return 'Reading & News';
}

const all = fs.readdirSync(batchesDir).filter((name) => name.endsWith('.mjs'));
const chosen = new Map();
for (const name of all) {
  const key = batchKey(name);
  const current = chosen.get(key);
  if (!current || precedence(name) > precedence(current)) chosen.set(key, name);
}
const batchFiles = [...chosen.values()].sort(
  (a, b) => batchStart(a) - batchStart(b) || a.localeCompare(b)
);
const batchCards = [];
for (const file of batchFiles) {
  const mod = await import(pathToFileURL(path.join(batchesDir, file)).href);
  if (!Array.isArray(mod.default)) throw new Error(`${file} must default-export an array`);
  batchCards.push(...mod.default);
}

let cards = [...foundation.cards, ...batchCards];
cards = applyConversationalChunkReplacements(cards).cards;
cards = applyModernLifeCoverage(cards).cards;
cards = applyRegisterAudit(cards, registerPolicy).cards;
cards = applyRomanizationToCards(cards, romanPolicy, registerPolicy);
cards = applyExampleSentences(cards).cards;

if (cards.length !== 2000) throw new Error(`browser v5 deck must contain 2000 cards; found ${cards.length}`);

const seenIds = new Set();
const browserCards = cards.map((card, index) => {
  if (!card.id || seenIds.has(card.id)) throw new Error(`duplicate/missing v5 id at ${index + 1}: ${card.id}`);
  seenIds.add(card.id);
  const out = {
    id: card.id,
    fa: card.fa,
    roman: card.roman,
    en: card.en,
    register: card.register,
    category: card.category,
    stage: stageFor(index + 1),
    exampleFa: card.exampleFa,
    exampleRoman: card.exampleRoman,
    exampleEn: card.exampleEn
  };
  if (card.spokenFa) out.spokenFa = card.spokenFa;
  if (card.formalFa) out.formalFa = card.formalFa;
  if (card.spokenRoman) out.spokenRoman = card.spokenRoman;
  if (card.formalRoman) out.formalRoman = card.formalRoman;
  return out;
});

const payload =
  '// Generated by tools/export-v5-browser-deck.mjs. Do not edit by hand.\n' +
  'window.FARSI_V5_DECK=' +
  JSON.stringify(browserCards) +
  ';\n';

fs.writeFileSync(path.join(root, 'data', 'v5-deck.js'), payload, 'utf8');
fs.writeFileSync(
  path.join(root, 'data', 'v5-deck-meta.json'),
  JSON.stringify({
    version: 'v5',
    cards: browserCards.length,
    generatedFrom: 'feature/v5-curriculum-foundation canonical pipeline',
    stableIds: true
  }, null, 2) + '\n',
  'utf8'
);
console.log(`exported browser v5 deck: ${browserCards.length} cards`);
